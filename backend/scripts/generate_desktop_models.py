"""Generate the Desktop types for shared, serialized Pydantic domain models.

Run from the repository root with backend/.venv/bin/python. Use --check in CI.
The RPC-only projections in desktop/src/api/types.ts remain hand maintained.
"""

from __future__ import annotations

import argparse
import json
import sys
import types
from datetime import datetime
from pathlib import Path
from typing import Any, get_args, get_origin

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.approval.models import (  # noqa: E402
    ApprovalRequest,
    ApprovalRequestStatus,
)
from app.automation.models import (  # noqa: E402
    Automation,
    AutomationStatus,
    Schedule,
    ScheduleKind,
)
from app.conversation.models import Conversation  # noqa: E402
from app.models.types import AgentMode  # noqa: E402
from app.run.models import Run, RunStatus  # noqa: E402
from app.task.models import (  # noqa: E402
    Task,
    TaskPriority,
    TaskStatus,
    TaskStep,
    TaskStepStatus,
)

OUTPUT = ROOT / "desktop" / "src" / "api" / "backendModels.generated.ts"
ENUMS = (
    RunStatus, AgentMode, TaskStatus, TaskPriority, TaskStepStatus,
    AutomationStatus, ScheduleKind, ApprovalRequestStatus,
)
MODELS = (Conversation, Run, TaskStep, Task, Schedule, Automation, ApprovalRequest)


def _typescript(annotation: Any) -> str:
    if annotation is Any:
        return "unknown"
    origin = get_origin(annotation)
    if origin in (types.UnionType,):
        return " | ".join(_typescript(part) for part in get_args(annotation))
    if origin in (tuple, list):
        item = _typescript(get_args(annotation)[0])
        return f"({item})[]" if " | " in item else f"{item}[]"
    if origin is dict:
        key, value = get_args(annotation)
        if key is not str:
            raise TypeError(f"unsupported dictionary key: {annotation}")
        return f"Record<string, {_typescript(value)}>"
    if annotation is str or annotation is datetime:
        return "string"
    if annotation is int or annotation is float:
        return "number"
    if annotation is bool:
        return "boolean"
    if annotation is type(None):
        return "null"
    if isinstance(annotation, type) and issubclass(annotation, (*ENUMS, *MODELS)):
        return annotation.__name__
    raise TypeError(f"unsupported model field type: {annotation}")


def render() -> str:
    lines = [
        "// Generated by backend/scripts/generate_desktop_models.py. Do not edit.",
        "// These are JSON shapes returned by Pydantic model_dump(mode='json').",
        "",
    ]
    for enum in ENUMS:
        values = " | ".join(json.dumps(value.value) for value in enum)
        lines.extend((f"export type {enum.__name__} = {values}", ""))
    for model in MODELS:
        lines.append(f"export interface {model.__name__} {{")
        for name, field in model.model_fields.items():
            lines.append(f"  {name}: {_typescript(field.annotation)}")
        lines.extend(("}", ""))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f"outdated generated Desktop model types: {OUTPUT}")
            return 1
        return 0
    OUTPUT.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
